import 'dart:io';

/// Optional verification & CI tool to validate that `pubspec.yaml`
/// contains a valid semantic version and matches expectations.
///
/// Note: Version synchronization is NOT required for application builds or runtime;
/// Flutter build tools and `AppVersion` automatically resolve versioning directly.
///
/// Usage:
///   dart run tool/sync_version.dart --check
///   dart run tool/sync_version.dart
void main(List<String> args) {
  final checkOnly = args.contains('--check');

  final pubspecFile = File('pubspec.yaml');
  if (!pubspecFile.existsSync()) {
    stderr.writeln('Error: pubspec.yaml not found in ${Directory.current.path}');
    exit(1);
  }

  final lines = pubspecFile.readAsLinesSync();
  String? rawVersion;

  final versionRegex = RegExp(r'^version:\s*([0-9]+\.[0-9]+\.[0-9]+)(?:\+([0-9]+))?$');

  for (final line in lines) {
    final trimmed = line.trim();
    if (trimmed.startsWith('version:')) {
      final match = versionRegex.firstMatch(trimmed);
      if (match == null) {
        stderr.writeln('Error: Invalid version format in pubspec.yaml: "$trimmed"');
        stderr.writeln('Expected format: version: X.Y.Z or version: X.Y.Z+BuildNumber (e.g. 1.2.0+3)');
        exit(1);
      }
      rawVersion = trimmed;
      break;
    }
  }

  if (rawVersion == null) {
    stderr.writeln('Error: No "version:" declaration found in pubspec.yaml');
    exit(1);
  }

  final match = versionRegex.firstMatch(rawVersion)!;
  final versionName = match.group(1)!;
  final versionCodeStr = match.group(2) ?? '1';
  final versionCode = int.tryParse(versionCodeStr);

  if (versionCode == null) {
    stderr.writeln('Error: Invalid build number "$versionCodeStr" in pubspec.yaml');
    exit(1);
  }

  final generatedContent = '''// This file is generated by tool/sync_version.dart from pubspec.yaml.
// Do not edit this file manually. Any changes will be overwritten.

/// Authoritative compile-time application version definitions synchronized with `pubspec.yaml`.
class AppVersion {
  AppVersion._();

  /// Semantic version name (e.g., '$versionName').
  /// Uses compile-time environment define if provided, defaulting to pubspec.yaml value.
  static const String versionName = String.fromEnvironment(
    'FLUTTER_BUILD_NAME',
    defaultValue: '$versionName',
  );

  /// Version build code / number (e.g., $versionCode).
  /// Uses compile-time environment define if provided, defaulting to pubspec.yaml value.
  static const int versionCode = int.fromEnvironment(
    'FLUTTER_BUILD_NUMBER',
    defaultValue: $versionCode,
  );

  /// Full version string (e.g., '$versionName+$versionCode').
  static const String fullVersion = '\$versionName+\$versionCode';
}
''';

  final targetFile = File('lib/core/config/app_version.dart');

  if (checkOnly) {
    if (!targetFile.existsSync()) {
      stderr.writeln('Check failed: lib/core/config/app_version.dart does not exist.');
      exit(1);
    }
    final currentContent = targetFile.readAsStringSync();
    if (currentContent.replaceAll('\r\n', '\n') != generatedContent.replaceAll('\r\n', '\n')) {
      stderr.writeln('Check failed: lib/core/config/app_version.dart is out of sync with pubspec.yaml ($versionName+$versionCode).');
      stderr.writeln('Run "dart run tool/sync_version.dart" to synchronize.');
      exit(1);
    }
    stdout.writeln('Version check passed: lib/core/config/app_version.dart is synchronized with pubspec.yaml ($versionName+$versionCode).');
    return;
  }

  targetFile.parent.createSync(recursive: true);
  targetFile.writeAsStringSync(generatedContent);
  stdout.writeln('Successfully synchronized AppVersion with pubspec.yaml: $versionName+$versionCode');
}
