class AppLocalizations {
  final Locale locale;

  AppLocalizations(this.locale);

  static AppLocalizations of(BuildContext context) {
    return Localizations.of<AppLocalizations>(context, AppLocalizations) ??
        AppLocalizations(const Locale('en'));
  }

  String translate(String key) {
    return AppStrings.get(key, locale: locale.languageCode);
  }

  String get prayerFajr => translate('fajr');
  String get prayerSunrise => translate('sunrise');
  String get prayerDhuhr => translate('dhuhr');
  String get prayerAsr => translate('asr');
  String get prayerMaghrib => translate('maghrib');
  String get prayerIsha => translate('isha');
}

class AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => ['en', 'ar'].contains(locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) async {
    return AppLocalizations(locale);
  }

  @override
  bool shouldReload(AppLocalizationsDelegate old) => false;
}
